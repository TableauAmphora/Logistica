GREATEST(0, res_siman_peru ) as res_siman_peru,
GREATEST(0, res_falabella - dev_falabella) as res_falabella,
GREATEST(0, res_falabella_colombia - dev_falabella_colombia) as res_falabella_colombia,
GREATEST(0, res_mayorista - dev_mayorista) as res_mayorista,
