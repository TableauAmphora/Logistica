fuente, 
'CUR' as whs_code,
item_code, 
total_cd, 
dev_multivende + dev_shopify as dev_multivende, 
dev_canal_directo, 
dev_mayorista, 
dev_dafiti, 
dev_falabella, 
dev_argentina, 
dev_peru, 
dev_falabella_colombia, 
dev_leonisa, 
dev_falabella_market,
