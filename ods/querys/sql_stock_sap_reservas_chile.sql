GREATEST(0, res_paris) as res_paris,
GREATEST(0, res_tienda) as res_tienda,
GREATEST(0, res_alianza) as res_alianza,
GREATEST(0, res_especial) as res_especial,
GREATEST(0, res_dafiti - dev_dafiti) as res_dafiti,
GREATEST(0, res_importaciones) as res_importaciones,
GREATEST(0, res_leonisa - dev_leonisa) as res_leonisa,
fecha_actualizacion as fecha_actualizacion_origen

FROM origen.hechos_stock_sap_reservas